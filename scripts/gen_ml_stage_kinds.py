"""Generate crates/spark-connect/src/ml/stage_kinds.rs from tests/golden/ml_api.json: the kind of
each JVM class of the stages of pyspark.ml (an estimator, a transformer, a model or an evaluator),
which a load of a meta-algorithm of PySpark's Python format reads its stages by, as the server's
`Read` of a JVM class needs its operator type.

    python scripts/gen_ml_stage_kinds.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# The classes of PySpark's Python format, which are no JVM classes.
PYTHON_CLASSES = {
    "Pipeline",
    "PipelineModel",
    "CrossValidator",
    "CrossValidatorModel",
    "TrainValidationSplit",
    "TrainValidationSplitModel",
    "OneVsRest",
    "OneVsRestModel",
}


def kind(name, entry):
    members = entry["members"]
    if "fit" in members:
        return "Estimator"
    if "evaluate" in members and "isLargerBetter" in members:
        return "Evaluator"
    if "transform" in members:
        return "Model" if name.endswith("Model") else "Transformer"
    return None


def main():
    api = json.loads((ROOT / "tests/golden/ml_api.json").read_text())
    rows = []
    for name, entry in sorted(api.items()):
        k = kind(name, entry)
        if k is None or name in PYTHON_CLASSES:
            continue
        jvm = entry["module"].replace("pyspark", "org.apache.spark", 1) + "." + name
        rows.append(f'    ("{jvm}", OperatorType::{k}),')
    out = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// @generated by scripts/gen_ml_stage_kinds.py from tests/golden/ml_api.json; do not edit.",
        "//! The kind of each JVM class of the stages of pyspark.ml 4.3.0, of which a load of a",
        "//! meta-algorithm reads its stages: the server's `Read` of a class needs its operator type.",
        "use super::OperatorType;",
        "",
        "/// Each JVM class of a stage of pyspark.ml and its operator type, by class name.",
        "pub(super) const STAGE_KINDS: &[(&str, OperatorType)] = &[",
        *rows,
        "];",
        "",
    ]
    (ROOT / "crates/spark-connect/src/ml/stage_kinds.rs").write_text("\n".join(out))


if __name__ == "__main__":
    main()
